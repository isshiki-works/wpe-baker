    GpuMediaFoundation(VkPhysicalDevice gpu, VkDevice device,
                       std::span<const std::string> extensions,
                       std::uint32_t width, std::uint32_t height)
        : device_(device),gpu_(gpu),width_(width),height_(height),
          word_width_(((width+3u)&~3u)/4u),bridge_height_(height*3u/2u) {
        for(const char* required:{VK_KHR_EXTERNAL_MEMORY_WIN32_EXTENSION_NAME,VK_KHR_WIN32_KEYED_MUTEX_EXTENSION_NAME})
            if(std::find(extensions.begin(),extensions.end(),required)==extensions.end())
                throw std::runtime_error(std::string("Media Foundation GPU encoding requires ")+required);
        get_handle_properties_=reinterpret_cast<PFN_vkGetMemoryWin32HandlePropertiesKHR>(
            vkGetDeviceProcAddr(device_,"vkGetMemoryWin32HandlePropertiesKHR"));
        if(!get_handle_properties_) throw std::runtime_error("vkGetMemoryWin32HandlePropertiesKHR unavailable");
        VkPhysicalDeviceExternalImageFormatInfo external{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_EXTERNAL_IMAGE_FORMAT_INFO};
        external.handleType=VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT;
        VkPhysicalDeviceImageFormatInfo2 format{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_IMAGE_FORMAT_INFO_2};
        format.pNext=&external;format.format=VK_FORMAT_R32_UINT;format.type=VK_IMAGE_TYPE_2D;
        format.tiling=VK_IMAGE_TILING_OPTIMAL;format.usage=VK_IMAGE_USAGE_TRANSFER_DST_BIT|VK_IMAGE_USAGE_SAMPLED_BIT;
        VkExternalImageFormatProperties external_properties{VK_STRUCTURE_TYPE_EXTERNAL_IMAGE_FORMAT_PROPERTIES};
        VkImageFormatProperties2 properties{VK_STRUCTURE_TYPE_IMAGE_FORMAT_PROPERTIES_2};properties.pNext=&external_properties;
        vk(vkGetPhysicalDeviceImageFormatProperties2(gpu_,&format,&properties),"query MF shared R32_UINT import");
        if(!(external_properties.externalMemoryProperties.externalMemoryFeatures&VK_EXTERNAL_MEMORY_FEATURE_IMPORTABLE_BIT) ||
           word_width_>properties.imageFormatProperties.maxExtent.width || bridge_height_>properties.imageFormatProperties.maxExtent.height)
            throw std::runtime_error("Media Foundation R32_UINT bridge texture cannot be imported at the requested dimensions");
        VkPhysicalDeviceIDProperties id{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_ID_PROPERTIES};
        VkPhysicalDeviceProperties2 physical{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2};physical.pNext=&id;
        vkGetPhysicalDeviceProperties2(gpu_,&physical);
        if(!id.deviceLUIDValid) throw std::runtime_error("Vulkan device has no valid LUID for Media Foundation");
        IDXGIFactory1* factory{};
        hr(CreateDXGIFactory1(IID_IDXGIFactory1,reinterpret_cast<void**>(&factory)),"create MF DXGI factory");
        IDXGIAdapter1* selected{};
        try {
            for(UINT index=0;;++index) {
                IDXGIAdapter1* candidate{};
                HRESULT result=factory->EnumAdapters1(index,&candidate);
                if(result==DXGI_ERROR_NOT_FOUND) break;
                hr(result,"enumerate MF DXGI adapter");
                DXGI_ADAPTER_DESC1 desc{};
                result=candidate->GetDesc1(&desc);
                if(result!=S_OK) {candidate->Release();hr(result,"describe MF DXGI adapter");}
                if(std::memcmp(&desc.AdapterLuid,id.deviceLUID,VK_LUID_SIZE)==0) {selected=candidate;break;}
                candidate->Release();
            }
            if(!selected) throw std::runtime_error("No D3D11 adapter matches the renderer Vulkan LUID");
            hr(D3D11CreateDevice(selected,D3D_DRIVER_TYPE_UNKNOWN,nullptr,
                D3D11_CREATE_DEVICE_BGRA_SUPPORT|D3D11_CREATE_DEVICE_VIDEO_SUPPORT,nullptr,0,D3D11_SDK_VERSION,
                &d3d_,nullptr,&context_),"create same-LUID MF D3D11 device");
            selected->Release();selected=nullptr;factory->Release();factory=nullptr;
            hr(d3d_->CreateComputeShader(kUnpackCs,sizeof(kUnpackCs),nullptr,&unpack_cs_),"create MF NV12 unpack shader");
            const std::uint32_t params[4]={width_,height_,word_width_,0};
            D3D11_BUFFER_DESC cbd{};cbd.ByteWidth=sizeof(params);cbd.Usage=D3D11_USAGE_IMMUTABLE;cbd.BindFlags=D3D11_BIND_CONSTANT_BUFFER;
            D3D11_SUBRESOURCE_DATA init_cb{params,0,0};
            hr(d3d_->CreateBuffer(&cbd,&init_cb,&params_cb_),"create MF NV12 unpack constant buffer");
            initBridge();
            hardware_=av_hwdevice_ctx_alloc(AV_HWDEVICE_TYPE_D3D11VA);
            if(!hardware_) throw std::bad_alloc();
            auto* hw=reinterpret_cast<AVHWDeviceContext*>(hardware_->data);
            auto* d3d=reinterpret_cast<AVD3D11VADeviceContext*>(hw->hwctx);
            d3d_->AddRef();d3d->device=d3d_;
            av(av_hwdevice_ctx_init(hardware_),"wrap MF D3D11 device");
            slots_[0]=makeSlot();
        } catch(...) {
            if(selected) selected->Release();
            if(factory) factory->Release();
            cleanup();
            throw;
        }
    }
    ~GpuMediaFoundation() {
        cleanup();
    }
    AVBufferRef* frames() const { return slots_[0]->frames; }
    AVBufferRef* hardware() const { return hardware_; }
    Slot* checkout() {
        for(auto& slot:slots_) {
            if(!slot) slot=makeSlot();
            if(!slot->in_use) {slot->in_use=true;return slot.get();}
        }
        return nullptr;
    }
    bool outstanding() const {
        return std::any_of(slots_.begin(),slots_.end(),[](const auto& slot){return slot && slot->in_use;});
    }
    void recordCopy(Slot&, VkCommandBuffer command, VkBuffer buffer,
                    std::uint32_t stride, std::uint32_t family) {
        (void)stride;
        VkImageMemoryBarrier before{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
        before.dstAccessMask=VK_ACCESS_TRANSFER_WRITE_BIT;
        before.oldLayout=bridge_written_ ? VK_IMAGE_LAYOUT_GENERAL : VK_IMAGE_LAYOUT_UNDEFINED;
        before.newLayout=VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;
        before.srcQueueFamilyIndex=VK_QUEUE_FAMILY_EXTERNAL;before.dstQueueFamilyIndex=family;
        before.image=bridge_image_;before.subresourceRange={VK_IMAGE_ASPECT_COLOR_BIT,0,1,0,1};
        vkCmdPipelineBarrier(command,VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT,VK_PIPELINE_STAGE_TRANSFER_BIT,0,0,nullptr,0,nullptr,1,&before);
        VkBufferImageCopy copy{};
        copy.bufferRowLength=word_width_;copy.bufferImageHeight=bridge_height_;
        copy.imageSubresource={VK_IMAGE_ASPECT_COLOR_BIT,0,0,1};copy.imageExtent={word_width_,bridge_height_,1};
        vkCmdCopyBufferToImage(command,buffer,bridge_image_,VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,1,&copy);
        VkImageMemoryBarrier after=before;after.srcAccessMask=VK_ACCESS_TRANSFER_WRITE_BIT;after.dstAccessMask=0;
        after.oldLayout=VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL;after.newLayout=VK_IMAGE_LAYOUT_GENERAL;
        after.srcQueueFamilyIndex=family;after.dstQueueFamilyIndex=VK_QUEUE_FAMILY_EXTERNAL;
        vkCmdPipelineBarrier(command,VK_PIPELINE_STAGE_TRANSFER_BIT,VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT,0,0,nullptr,0,nullptr,1,&after);
    }
    void holdForEncoder(Slot& slot, std::int64_t pts) {
        hr(bridge_mutex_->AcquireSync(1,30000),"acquire MF bridge texture after conversion");
        bridge_acquired_=true;bridge_written_=true;
        context_->CSSetShader(unpack_cs_,nullptr,0);
        context_->CSSetConstantBuffers(0,1,&params_cb_);
        context_->CSSetShaderResources(0,1,&bridge_srv_);
        ID3D11UnorderedAccessView* uavs[2]={slot.uav_y,slot.uav_uv};
        context_->CSSetUnorderedAccessViews(0,2,uavs,nullptr);
        context_->Dispatch((word_width_+7u)/8u,(height_+7u)/8u,1u);
        ID3D11ShaderResourceView* null_srv[1]={nullptr};
        ID3D11UnorderedAccessView* null_uav[2]={nullptr,nullptr};
        context_->CSSetShaderResources(0,1,null_srv);
        context_->CSSetUnorderedAccessViews(0,2,null_uav,nullptr);
        context_->Flush();
        hr(bridge_mutex_->ReleaseSync(0),"release MF bridge texture");
        bridge_acquired_=false;
        slot.pts=pts;slot.sent=true;
    }
    void packetReturned(std::int64_t pts) {
        for(auto& slot:slots_) if(slot && slot->sent && slot->pts==pts) {
            slot->sent=false;slot->in_use=false;slot->pts=AV_NOPTS_VALUE;
            return;
        }
        throw std::runtime_error("Media Foundation packet timestamp has no outstanding input: "+std::to_string(pts));
    }
