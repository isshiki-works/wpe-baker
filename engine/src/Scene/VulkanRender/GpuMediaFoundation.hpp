    void initBridge() {
        D3D11_TEXTURE2D_DESC desc{};desc.Width=word_width_;desc.Height=bridge_height_;desc.MipLevels=1;desc.ArraySize=1;
        desc.Format=DXGI_FORMAT_R32_UINT;desc.SampleDesc.Count=1;desc.Usage=D3D11_USAGE_DEFAULT;
        desc.BindFlags=D3D11_BIND_SHADER_RESOURCE;
        desc.MiscFlags=D3D11_RESOURCE_MISC_SHARED_NTHANDLE|D3D11_RESOURCE_MISC_SHARED_KEYEDMUTEX;
        hr(d3d_->CreateTexture2D(&desc,nullptr,&bridge_texture_),"create MF shared R32_UINT bridge texture");
        hr(d3d_->CreateShaderResourceView(bridge_texture_,nullptr,&bridge_srv_),"create MF bridge SRV");
        IDXGIResource1* resource{};
        hr(bridge_texture_->QueryInterface(IID_IDXGIResource1,reinterpret_cast<void**>(&resource)),"query MF bridge resource");
        const auto shared_result=resource->CreateSharedHandle(nullptr,DXGI_SHARED_RESOURCE_READ|DXGI_SHARED_RESOURCE_WRITE,nullptr,&bridge_shared_);
        resource->Release();hr(shared_result,"export MF bridge shared handle");
        hr(bridge_texture_->QueryInterface(IID_IDXGIKeyedMutex,reinterpret_cast<void**>(&bridge_mutex_)),"query MF bridge keyed mutex");
        VkExternalMemoryImageCreateInfo external{VK_STRUCTURE_TYPE_EXTERNAL_MEMORY_IMAGE_CREATE_INFO};
        external.handleTypes=VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT;
        VkImageCreateInfo image{VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};image.pNext=&external;image.imageType=VK_IMAGE_TYPE_2D;
        image.format=VK_FORMAT_R32_UINT;image.extent={word_width_,bridge_height_,1};image.mipLevels=1;image.arrayLayers=1;
        image.samples=VK_SAMPLE_COUNT_1_BIT;image.tiling=VK_IMAGE_TILING_OPTIMAL;
        image.usage=VK_IMAGE_USAGE_TRANSFER_DST_BIT|VK_IMAGE_USAGE_SAMPLED_BIT;
        vk(vkCreateImage(device_,&image,nullptr,&bridge_image_),"create imported MF bridge image");
        VkMemoryRequirements requirements{};vkGetImageMemoryRequirements(device_,bridge_image_,&requirements);
        VkMemoryWin32HandlePropertiesKHR handle{VK_STRUCTURE_TYPE_MEMORY_WIN32_HANDLE_PROPERTIES_KHR};
        vk(get_handle_properties_(device_,VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT,bridge_shared_,&handle),"query MF bridge import memory types");
        VkPhysicalDeviceMemoryProperties memory{};vkGetPhysicalDeviceMemoryProperties(gpu_,&memory);
        const auto bits=requirements.memoryTypeBits&handle.memoryTypeBits;
        std::uint32_t index=0;while(index<memory.memoryTypeCount && !(bits&(1u<<index))) ++index;
        if(index==memory.memoryTypeCount) throw std::runtime_error("No compatible memory type for MF bridge texture");
        VkMemoryDedicatedAllocateInfo dedicated{VK_STRUCTURE_TYPE_MEMORY_DEDICATED_ALLOCATE_INFO};dedicated.image=bridge_image_;
        VkImportMemoryWin32HandleInfoKHR imported{VK_STRUCTURE_TYPE_IMPORT_MEMORY_WIN32_HANDLE_INFO_KHR};
        imported.pNext=&dedicated;imported.handleType=VK_EXTERNAL_MEMORY_HANDLE_TYPE_D3D11_TEXTURE_BIT;imported.handle=bridge_shared_;
        VkMemoryAllocateInfo allocation{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};allocation.pNext=&imported;
        allocation.allocationSize=requirements.size;allocation.memoryTypeIndex=index;
        vk(vkAllocateMemory(device_,&allocation,nullptr,&bridge_memory_),"import MF bridge texture memory");
        vk(vkBindImageMemory(device_,bridge_image_,bridge_memory_,0),"bind MF bridge texture memory");
    }
    std::unique_ptr<Slot> makeSlot() {
        auto slot=std::make_unique<Slot>();slot->memory=bridge_memory_;
        D3D11_TEXTURE2D_DESC desc{};desc.Width=width_;desc.Height=height_;desc.MipLevels=1;desc.ArraySize=1;
        desc.Format=DXGI_FORMAT_NV12;desc.SampleDesc.Count=1;desc.Usage=D3D11_USAGE_DEFAULT;
        desc.BindFlags=D3D11_BIND_SHADER_RESOURCE|D3D11_BIND_UNORDERED_ACCESS;
        hr(d3d_->CreateTexture2D(&desc,nullptr,&slot->texture),"create MF native NV12 texture");
        D3D11_UNORDERED_ACCESS_VIEW_DESC uav{};uav.Format=DXGI_FORMAT_R8_UINT;uav.ViewDimension=D3D11_UAV_DIMENSION_TEXTURE2D;
        hr(d3d_->CreateUnorderedAccessView(slot->texture,&uav,&slot->uav_y),"create MF NV12 luma UAV");
        uav.Format=DXGI_FORMAT_R8G8_UINT;
        hr(d3d_->CreateUnorderedAccessView(slot->texture,&uav,&slot->uav_uv),"create MF NV12 chroma UAV");
        slot->frames=av_hwframe_ctx_alloc(hardware_);if(!slot->frames) throw std::bad_alloc();
        auto* frames=reinterpret_cast<AVHWFramesContext*>(slot->frames->data);
        frames->format=AV_PIX_FMT_D3D11;frames->sw_format=AV_PIX_FMT_NV12;
        frames->width=static_cast<int>(width_);frames->height=static_cast<int>(height_);frames->initial_pool_size=1;
        auto* d3d_frames=reinterpret_cast<AVD3D11VAFramesContext*>(frames->hwctx);
        slot->texture->AddRef();d3d_frames->texture=slot->texture;
        av(av_hwframe_ctx_init(slot->frames),"prepare MF NV12 texture frame context");
        slot->frame=av_frame_alloc();if(!slot->frame) throw std::bad_alloc();
        av(av_hwframe_get_buffer(slot->frames,slot->frame,0),"wrap MF NV12 texture frame");
        return slot;
    }
    void cleanup() {
        for(auto& slot:slots_) slot.reset();
        av_buffer_unref(&hardware_);
        if(bridge_acquired_ && bridge_mutex_) {bridge_mutex_->ReleaseSync(0);bridge_acquired_=false;}
        if(bridge_image_) {vkDestroyImage(device_,bridge_image_,nullptr);bridge_image_=VK_NULL_HANDLE;}
        if(bridge_memory_) {vkFreeMemory(device_,bridge_memory_,nullptr);bridge_memory_=VK_NULL_HANDLE;}
        if(bridge_shared_) {CloseHandle(bridge_shared_);bridge_shared_=nullptr;}
        if(bridge_mutex_) {bridge_mutex_->Release();bridge_mutex_=nullptr;}
        if(bridge_srv_) {bridge_srv_->Release();bridge_srv_=nullptr;}
        if(bridge_texture_) {bridge_texture_->Release();bridge_texture_=nullptr;}
        if(params_cb_) {params_cb_->Release();params_cb_=nullptr;}
        if(unpack_cs_) {unpack_cs_->Release();unpack_cs_=nullptr;}
        if(context_) {context_->Release();context_=nullptr;}
        if(d3d_) {d3d_->Release();d3d_=nullptr;}
    }
