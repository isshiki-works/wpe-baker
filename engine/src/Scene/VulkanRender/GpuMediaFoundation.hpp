    static void hr(HRESULT result, const char* operation) {
        if (result != S_OK) {
            std::ostringstream text;
            text << operation << ": HRESULT=0x" << std::hex << static_cast<std::uint32_t>(result);
            throw std::runtime_error(text.str());
        }
    }
    static void vk(VkResult result, const char* operation) {
        if (result != VK_SUCCESS)
            throw std::runtime_error(std::string(operation)+": VkResult="+std::to_string(result));
    }
    static void av(int result, const char* operation) {
        if (result >= 0) return;
        char error[AV_ERROR_MAX_STRING_SIZE]{};
        av_strerror(result,error,sizeof(error));
        throw std::runtime_error(std::string(operation)+": AVERROR="+std::to_string(result)+" "+error);
    }
