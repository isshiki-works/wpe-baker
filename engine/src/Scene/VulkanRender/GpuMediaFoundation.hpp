    struct Slot {
        VkDeviceMemory memory{};
        ID3D11Texture2D* texture{};
        ID3D11UnorderedAccessView* uav_y{};
        ID3D11UnorderedAccessView* uav_uv{};
        AVBufferRef* frames{};
        AVFrame* frame{};
        bool in_use{}, sent{};
        std::int64_t pts{AV_NOPTS_VALUE};
        ~Slot() {
            av_frame_free(&frame);
            av_buffer_unref(&frames);
            if(uav_uv) uav_uv->Release();
            if(uav_y) uav_y->Release();
            if(texture) texture->Release();
        }
    };
